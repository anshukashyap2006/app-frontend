import jsPDF from "jspdf";

export function downloadCopyAsPDF({ type, subject, body, filename }) {
  // Create a new jsPDF instance
  // Default is portrait, A4 size, using points/mm/etc. We'll use defaults (A4).
  const doc = new jsPDF();
  
  // Settings
  const margin = 15;
  const pageWidth = doc.internal.pageSize.getWidth();
  const maxLineWidth = pageWidth - margin * 2;
  const lineHeight = 7;
  let cursorY = margin;

  // Set initial font
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);

  // Helper function to handle page breaks
  const checkPageBreak = (addedHeight) => {
    if (cursorY + addedHeight > doc.internal.pageSize.getHeight() - margin) {
      doc.addPage();
      cursorY = margin;
    }
  };

  // Header separator
  const separator = "---------------------------------------";
  doc.text(separator, margin, cursorY);
  cursorY += lineHeight;

  // Title / Type
  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text(type.toUpperCase(), margin, cursorY);
  cursorY += lineHeight * 1.5;

  // Subject line (if applicable)
  if (subject) {
    doc.setFont("helvetica", "bold");
    doc.setFontSize(11);
    doc.text(`Subject: ${subject}`, margin, cursorY);
    cursorY += lineHeight * 1.5;
  }

  // Body content
  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  
  // Split the body into paragraphs
  const paragraphs = body.split("\n");
  
  paragraphs.forEach(para => {
    // Break the paragraph into lines that fit the page width
    const lines = doc.splitTextToSize(para, maxLineWidth);
    
    lines.forEach(line => {
      checkPageBreak(lineHeight);
      doc.text(line, margin, cursorY);
      cursorY += lineHeight;
    });
    
    // Add extra space after paragraphs, unless the paragraph was empty (which means it was a double newline in original text)
    if (para.trim() === "") {
      checkPageBreak(lineHeight);
      cursorY += lineHeight / 2;
    } else {
      cursorY += lineHeight / 2;
    }
  });

  // Footer separator
  cursorY += lineHeight;
  checkPageBreak(lineHeight * 3);
  doc.setFontSize(10);
  doc.text(separator, margin, cursorY);
  cursorY += lineHeight;

  // Branding footer
  doc.setFont("helvetica", "italic");
  doc.text("Generated by CopyCraft", margin, cursorY);

  // Save the PDF
  doc.save(filename || "CopyCraft_Generated.pdf");
}
